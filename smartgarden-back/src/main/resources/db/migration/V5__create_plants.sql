-- Jardim virtual: cada planta tem uma "caixa d'água" estimada que esvazia conforme o clima medido pelo sensor.
-- Modelo: perda (mL/h) = k × VPD (kPa). k é calibrado pesando vasos reais.
create table if not exists plants (
    id bigint generated by default as identity primary key,
    plant_code varchar(60) not null unique,
    name varchar(120) not null,
    scientific_name varchar(160),
    spot varchar(200),
    device_id bigint,
    active boolean not null default true,

    -- parâmetros da espécie e do vaso
    water_capacity_ml double precision not null,
    irrigation_threshold_percent double precision not null,
    irrigation_ml integer not null,
    loss_coefficient double precision not null,
    auto_irrigation boolean not null default true,
    temperature_min_c double precision,
    temperature_max_c double precision,
    humidity_min_percent double precision,
    humidity_max_percent double precision,

    -- estado da estimativa
    estimated_water_ml double precision not null,
    estimated_at timestamp with time zone not null,
    last_vpd_kpa double precision,
    needs_water boolean not null default false,
    last_watered_at timestamp with time zone,

    -- pesagem e calibração
    full_weight_g double precision,
    last_weight_g double precision,
    last_weighed_at timestamp with time zone,
    estimated_loss_since_weighing_ml double precision not null default 0,
    vpd_hours_since_weighing double precision not null default 0,
    watered_since_weighing boolean not null default false,
    calibration_samples integer not null default 0,
    suggested_coefficient double precision,
    mean_error_percent double precision,

    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint fk_plants_device
        foreign key (device_id) references devices (id) on delete set null
);

create index if not exists idx_plants_device on plants (device_id);

create table if not exists plant_records (
    id bigint generated by default as identity primary key,
    plant_id bigint not null,
    record_type varchar(20) not null,
    recorded_at timestamp with time zone not null,
    automatic boolean not null default false,
    weight_g double precision,
    full_pot boolean,
    water_ml integer,
    drained boolean,
    estimated_water_percent double precision,
    measured_water_percent double precision,
    estimated_loss_ml double precision,
    measured_loss_ml double precision,
    measured_coefficient double precision,
    note varchar(500),
    created_at timestamp with time zone not null,
    constraint fk_plant_records_plant
        foreign key (plant_id) references plants (id) on delete cascade
);

create index if not exists idx_plant_records_plant_recorded_at
    on plant_records (plant_id, recorded_at desc);
