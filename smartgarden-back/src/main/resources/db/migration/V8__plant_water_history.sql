-- Curva da água estimada de cada planta, para o gráfico de estimado × medido na ficha da planta.
-- Um ponto a cada 10 minutos de leituras, mais um antes e um depois de cada rega, irrigação ou pesagem,
-- para o degrau aparecer no lugar certo (na pesagem, o degrau é a diferença entre o estimado e o medido).
create table if not exists plant_water_history (
    id bigint generated by default as identity primary key,
    plant_id bigint not null,
    recorded_at timestamp with time zone not null,
    water_ml double precision not null,
    water_percent double precision not null,
    constraint fk_plant_water_history_plant
        foreign key (plant_id) references plants (id) on delete cascade
);

create index if not exists idx_plant_water_history_plant_recorded_at
    on plant_water_history (plant_id, recorded_at);

-- hora do último ponto guardado, para não consultar a tabela a cada leitura
alter table plants add column if not exists water_history_at timestamp with time zone;
